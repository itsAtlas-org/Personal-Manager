//! The Atlas mod-signing keys (Mods spec D15, §1.1) and the key-id gate.
//!
//! PM embeds two minisign Ed25519 public keys: the **main** key, whose private half signs in the
//! pm-mods `sign` job, and the **rollover** key, whose private half never leaves Bobby's password
//! manager. Embedding a key is a one-way door: every PM ever shipped trusts it. With two, losing or
//! leaking the main key costs a signed index instead of a release: an index signed by the rollover
//! key revokes the main key's id, PM records that per machine, and from then on refuses the main
//! key for indexes and packages alike. Nothing can revoke the rollover key (a leaked main key
//! must not be able to lock the rollover out), and nothing un-revokes a key.
//!
//! The trusted set is the embedded keys minus the ids this machine has seen revoked
//! ([`KeyRing::trusted`]), so every signature PM checks, a package's ([`super::package::verify`]
//! through the ledger's `install_package`) or the index's ([`super::index::verify_index`]), sees
//! the same set.
//!
//! A key id is minisign's: the 8 bytes after the two algorithm bytes of the key (and of every
//! signature it makes), read as a little-endian integer and printed as 16 uppercase hex digits.

// The ledger's install path and the index are the callers, and neither has a production caller
// until slice 5's fetcher and slice 6's Mods tab.
#![cfg_attr(not(test), allow(dead_code))]

use std::collections::BTreeSet;
use std::fmt;
use std::sync::OnceLock;

use base64::{engine::general_purpose::STANDARD as B64, Engine};
use minisign_verify::PublicKey;

/// What a key is for, which decides what an index it signs may revoke ([`super::index`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum KeyRole {
    /// Signs in CI. Revocable by the rollover key.
    Main,
    /// Kept offline. The only key whose index may revoke another; never revocable itself.
    Rollover,
    /// A dev build's own test key ([`dev_test_key`]), for live tests against a local index. Signs,
    /// can't revoke; a rollover-signed index can revoke it.
    DevTest,
}

/// One embedded key as the build carries it.
#[derive(Debug, Clone, Copy)]
pub struct EmbeddedKey {
    pub role: KeyRole,
    /// The key id the decoded key must have, as minisign prints it.
    pub id: &'static str,
    /// The base64 public key: the second line of the Tauri-generated `.pub` file once that file is
    /// base64-decoded.
    pub public: &'static str,
}

/// The two Atlas mod keys (spec D15), generated by Bobby on 2026-11-05 (build log, "The Atlas mod
/// signing keys"). **A one-way door:** every PM that ships with these trusts them until a signed
/// revocation says otherwise, so they change only in a release Bobby asks for.
pub const ATLAS_MOD_KEYS: [EmbeddedKey; 2] = [
    EmbeddedKey {
        role: KeyRole::Main,
        id: "95B83457064D517B",
        public: "RWR7UU0GVzS4lT3ufWzzf1KvC/kqXW/23dyEdYpTHVvpHOg4d4LrMRTe",
    },
    EmbeddedKey {
        role: KeyRole::Rollover,
        id: "993CE0152A3E4E8C",
        public: "RWSMTj4qFeA8maIDkSNH7pMwICiuA2PEmjQOEyAwn8PDXHA5ztfNy8qW",
    },
];

/// The dev-build-only variable naming a test key (decision 9 of the 2026-11-11 plan).
pub const DEV_TEST_KEY_VAR: &str = "PM_MODS_TEST_KEY";

/// A minisign key id.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct KeyId(u64);

impl KeyId {
    /// From the 8 key-id bytes as they sit in a key or a signature.
    pub fn from_bytes(bytes: [u8; 8]) -> Self {
        Self(u64::from_le_bytes(bytes))
    }

    /// Exactly 16 uppercase hex digits, the one spelling minisign prints and the index writes.
    pub fn parse(s: &str) -> Option<Self> {
        let shaped = s.len() == 16 && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'A'..=b'F'));
        shaped.then(|| u64::from_str_radix(s, 16).ok().map(Self))?
    }
}

impl fmt::Display for KeyId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:016X}", self.0)
    }
}

/// A key PM may trust, with its id and role.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AtlasKey {
    pub role: KeyRole,
    pub id: KeyId,
    pub key: PublicKey,
}

/// Decode a minisign public key ("Ed", the key id, the 32-byte Ed25519 key) and read its id.
/// `None` for anything else.
pub fn decode_public(base64: &str) -> Option<(KeyId, PublicKey)> {
    let bin = B64.decode(base64).ok()?;
    if bin.len() != 42 || bin[..2] != *b"Ed" {
        return None;
    }
    let id = KeyId::from_bytes(bin[2..10].try_into().ok()?);
    let key = PublicKey::from_base64(base64).ok()?;
    Some((id, key))
}

/// The embedded keys, decoded once. A key that doesn't decode to its recorded id is left out and
/// logged, so a mistyped constant makes PM trust fewer keys, never a different one; the tests pin
/// both, so a build can't ship that way.
pub fn embedded() -> &'static [AtlasKey] {
    static KEYS: OnceLock<Vec<AtlasKey>> = OnceLock::new();
    KEYS.get_or_init(|| decode_embedded(&ATLAS_MOD_KEYS))
}

fn decode_embedded(keys: &[EmbeddedKey]) -> Vec<AtlasKey> {
    let mut out = Vec::new();
    for k in keys {
        match decode_public(k.public) {
            Some((id, key)) if id.to_string() == k.id => out.push(AtlasKey {
                role: k.role,
                id,
                key,
            }),
            _ => eprintln!(
                "mods: the embedded {:?} key {} doesn't decode to its id; it is not trusted",
                k.role, k.id
            ),
        }
    }
    out
}

/// Every key this PM holds, trusted or revoked: the embedded keys, plus a dev build's test key.
#[derive(Debug, Clone)]
pub struct KeyRing {
    keys: Vec<AtlasKey>,
}

impl KeyRing {
    /// The Atlas keys and, in a dev build pointed at another data folder, its test key.
    pub fn atlas(dev: Option<AtlasKey>) -> Self {
        Self::of(embedded().iter().cloned().chain(dev))
    }

    /// This machine's ring: [`KeyRing::atlas`] with [`dev_test_key`].
    pub fn machine() -> Self {
        Self::atlas(dev_test_key())
    }

    /// The keys in order. A second key with an id already held is left out, so one id always means
    /// one key and one role.
    pub(crate) fn of(keys: impl IntoIterator<Item = AtlasKey>) -> Self {
        let mut held: Vec<AtlasKey> = Vec::new();
        for k in keys {
            if !held.iter().any(|h| h.id == k.id) {
                held.push(k);
            }
        }
        Self { keys: held }
    }

    /// The key-id gate: every held key whose id isn't revoked.
    pub fn trusted(&self, revoked: &BTreeSet<KeyId>) -> TrustedKeys {
        let trusted: Vec<AtlasKey> = self
            .keys
            .iter()
            .filter(|k| !revoked.contains(&k.id))
            .cloned()
            .collect();
        TrustedKeys {
            publics: trusted.iter().map(|k| k.key.clone()).collect(),
            trusted,
            known: self.keys.iter().map(|k| (k.id, k.role)).collect(),
        }
    }
}

/// The keys PM trusts right now: built only by [`KeyRing::trusted`], so a signature check can't
/// be handed a revoked key by mistake.
#[derive(Debug, Clone)]
pub struct TrustedKeys {
    trusted: Vec<AtlasKey>,
    publics: Vec<PublicKey>,
    /// Every held key, revoked ones included, for what an index may revoke.
    known: Vec<(KeyId, KeyRole)>,
}

impl TrustedKeys {
    /// The public keys, in the order a verifier's signer index refers to.
    pub fn public_keys(&self) -> &[PublicKey] {
        &self.publics
    }

    /// The key at a verifier's signer index.
    pub fn signer(&self, index: usize) -> Option<&AtlasKey> {
        self.trusted.get(index)
    }

    pub fn trusts(&self, id: KeyId) -> bool {
        self.trusted.iter().any(|k| k.id == id)
    }

    /// The role of a key this PM holds, whether it is still trusted or not.
    pub fn role_of(&self, id: KeyId) -> Option<KeyRole> {
        self.known.iter().find(|(k, _)| *k == id).map(|(_, r)| *r)
    }

    /// For the package and ledger tests, where only the keys matter: each key gets a placeholder id
    /// and the main role.
    #[cfg(test)]
    pub(crate) fn of_test_keys(keys: &[PublicKey]) -> Self {
        let ring = KeyRing::of(keys.iter().enumerate().map(|(i, key)| AtlasKey {
            role: KeyRole::Main,
            id: KeyId(i as u64 + 1),
            key: key.clone(),
        }));
        ring.trusted(&BTreeSet::new())
    }
}

/// Whether a dev-only safety-list override may apply: a debug build, pointed at another data folder
/// with `PM_DATA_DIR`. The second condition matters: the seen seq and the revocations are kept per
/// machine and never go down, so a test index read into the real data folder would make the
/// installed PM refuse the real index (or a test rotation would revoke the real main key) for good.
pub fn dev_overrides_allowed(debug_build: bool, data_dir_overridden: bool) -> bool {
    debug_build && data_dir_overridden
}

/// A dev-only setting for testing the safety list (the test key here, the fetcher's index URL):
/// the variable's value when [`dev_overrides_allowed`], else `None`. A release build never reads
/// the variable.
pub fn dev_setting(var: &str) -> Option<String> {
    #[cfg(debug_assertions)]
    {
        if !dev_overrides_allowed(true, crate::paths::data_dir_overridden()) {
            return None;
        }
        std::env::var(var).ok().filter(|v| !v.trim().is_empty())
    }
    #[cfg(not(debug_assertions))]
    {
        let _ = var;
        None
    }
}

/// A dev build's test key ([`DEV_TEST_KEY_VAR`]), so live tests L6 and L14 can sign their own
/// indexes and packages and never touch the public index. Logged and ignored when malformed.
pub fn dev_test_key() -> Option<AtlasKey> {
    let value = dev_setting(DEV_TEST_KEY_VAR)?;
    match parse_dev_test_key(&value, embedded()) {
        Ok(key) => {
            eprintln!("mods: trusting the dev test key {} as well", key.id);
            Some(key)
        }
        Err(why) => {
            eprintln!("mods: {DEV_TEST_KEY_VAR} ignored: {why}");
            None
        }
    }
}

/// A test key from its base64 public key. Refused when it isn't one, or when its id is an
/// embedded key's (it would stand in for that key, role and all).
pub fn parse_dev_test_key(base64: &str, embedded: &[AtlasKey]) -> Result<AtlasKey, &'static str> {
    let (id, key) = decode_public(base64.trim()).ok_or("not a minisign public key")?;
    if embedded.iter().any(|k| k.id == id) {
        return Err("it has an Atlas key's id");
    }
    Ok(AtlasKey {
        role: KeyRole::DevTest,
        id,
        key,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mods::package::tests::TestKey;

    fn id(s: &str) -> KeyId {
        KeyId::parse(s).unwrap()
    }

    /// The one-way door, pinned: both embedded keys decode, to the ids Bobby's `.pub` files print.
    #[test]
    fn the_embedded_keys_decode_to_their_recorded_ids() {
        let keys = embedded();
        assert_eq!(keys.len(), 2, "both keys decode");
        assert_eq!(
            (keys[0].role, keys[0].id.to_string().as_str()),
            (KeyRole::Main, "95B83457064D517B")
        );
        assert_eq!(
            (keys[1].role, keys[1].id.to_string().as_str()),
            (KeyRole::Rollover, "993CE0152A3E4E8C")
        );
        assert_ne!(keys[0].id, keys[1].id);
        assert_ne!(keys[0].key, keys[1].key);
        // Straight from the constants too, so the check doesn't rest on `embedded()` alone.
        for k in ATLAS_MOD_KEYS {
            let (got, _) = decode_public(k.public).unwrap();
            assert_eq!(got.to_string(), k.id);
        }
    }

    /// Spec §1.1: neither mod key may be the updater's, whose id `tauri.conf.json` carries.
    #[test]
    fn the_mod_keys_are_not_the_updater_key() {
        let conf: serde_json::Value =
            serde_json::from_str(include_str!("../../tauri.conf.json")).unwrap();
        let pub_file = B64
            .decode(conf["plugins"]["updater"]["pubkey"].as_str().unwrap())
            .unwrap();
        let pub_file = String::from_utf8(pub_file).unwrap();
        let line = pub_file.lines().nth(1).unwrap();
        let (updater, _) = decode_public(line).unwrap();
        assert_eq!(updater.to_string(), "B208FB553375F35D");
        for k in embedded() {
            assert_ne!(k.id, updater, "{:?}", k.role);
        }
    }

    #[test]
    fn a_key_that_doesnt_decode_to_its_id_is_left_out() {
        let main = ATLAS_MOD_KEYS[0];
        let keys = decode_embedded(&[
            EmbeddedKey {
                id: "993CE0152A3E4E8C",
                ..main
            },
            EmbeddedKey {
                public: "RWR7UU0GVzS4lT3ufWzzf1KvC/kqXW/23dyEdYpTHVvpHOg4d4LrMRT",
                ..main
            },
            main,
        ]);
        assert_eq!(keys.len(), 1);
        assert_eq!(keys[0].id, id("95B83457064D517B"));
    }

    #[test]
    fn key_ids_have_one_spelling() {
        let k = id("95B83457064D517B");
        assert_eq!(k.to_string(), "95B83457064D517B");
        assert_eq!(
            KeyId::from_bytes([0x7b, 0x51, 0x4d, 0x06, 0x57, 0x34, 0xb8, 0x95]),
            k
        );
        for bad in [
            "",
            "95b83457064d517b",
            "95B83457064D517",
            "95B83457064D517B0",
            "95B83457064D517G",
            " 95B83457064D517B",
            "+5B83457064D517B",
        ] {
            assert_eq!(KeyId::parse(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn only_minisign_ed25519_public_keys_decode() {
        let t = TestKey::new();
        let (got, key) = decode_public(&t.public_base64()).unwrap();
        assert_eq!(got, KeyId::from_bytes(t.id));
        assert_eq!(key, t.public());
        let mut bin = B64.decode(t.public_base64()).unwrap();
        bin[1] = b'D'; // "ED" is a signature's algorithm, never a key's
        assert!(decode_public(&B64.encode(&bin)).is_none());
        bin.truncate(41);
        assert!(decode_public(&B64.encode(&bin)).is_none());
        assert!(decode_public("not base64!").is_none());
        assert!(decode_public("").is_none());
    }

    /// The gate: a revoked id leaves the trusted set and stays known; the rest are untouched.
    #[test]
    fn a_revoked_id_is_no_longer_trusted() {
        let ring = KeyRing::atlas(None);
        let all = ring.trusted(&BTreeSet::new());
        assert_eq!(all.public_keys().len(), 2);
        let main = id("95B83457064D517B");
        let rollover = id("993CE0152A3E4E8C");
        assert!(all.trusts(main) && all.trusts(rollover));

        let after = ring.trusted(&BTreeSet::from([main]));
        assert!(!after.trusts(main));
        assert!(after.trusts(rollover));
        assert_eq!(after.public_keys().len(), 1);
        assert_eq!(after.signer(0).unwrap().id, rollover);
        assert_eq!(after.public_keys()[0], after.signer(0).unwrap().key);
        // Still known, so an index naming it is understood.
        assert_eq!(after.role_of(main), Some(KeyRole::Main));
        assert_eq!(after.role_of(id("0000000000000001")), None);
        // An id PM never held changes nothing.
        let unknown = ring.trusted(&BTreeSet::from([id("0123456789ABCDEF")]));
        assert_eq!(unknown.public_keys().len(), 2);
    }

    #[test]
    fn one_id_means_one_key() {
        let a = TestKey::new();
        let twin = TestKey {
            id: a.id,
            ..TestKey::new()
        };
        let ring = KeyRing::of([
            AtlasKey {
                role: KeyRole::Main,
                id: KeyId::from_bytes(a.id),
                key: a.public(),
            },
            AtlasKey {
                role: KeyRole::Rollover,
                id: KeyId::from_bytes(twin.id),
                key: twin.public(),
            },
        ]);
        let t = ring.trusted(&BTreeSet::new());
        assert_eq!(t.public_keys(), &[a.public()]);
        assert_eq!(t.role_of(KeyId::from_bytes(a.id)), Some(KeyRole::Main));
    }

    #[test]
    fn a_dev_test_key_joins_the_ring_and_can_be_revoked() {
        let t = TestKey::new();
        let dev = parse_dev_test_key(&format!(" {}\n", t.public_base64()), embedded()).unwrap();
        assert_eq!(dev.role, KeyRole::DevTest);
        let ring = KeyRing::atlas(Some(dev.clone()));
        assert_eq!(ring.trusted(&BTreeSet::new()).public_keys().len(), 3);
        assert!(!ring.trusted(&BTreeSet::from([dev.id])).trusts(dev.id));
        // Never in a stranger's shape, and never standing in for an Atlas key.
        assert!(parse_dev_test_key("RWQ=", embedded()).is_err());
        assert!(parse_dev_test_key(ATLAS_MOD_KEYS[0].public, embedded()).is_err());
        assert!(parse_dev_test_key(ATLAS_MOD_KEYS[1].public, embedded()).is_err());
    }

    /// Whatever this run's environment, the machine's ring is the two Atlas keys, plus at most a
    /// test key that isn't one of them.
    #[test]
    fn the_machine_ring_holds_the_atlas_keys() {
        let t = KeyRing::machine().trusted(&BTreeSet::new());
        let n = t.public_keys().len();
        assert!(n == 2 || n == 3, "{n}");
        assert_eq!(t.role_of(id("95B83457064D517B")), Some(KeyRole::Main));
        assert_eq!(t.role_of(id("993CE0152A3E4E8C")), Some(KeyRole::Rollover));
        if n == 3 {
            assert_eq!(t.signer(2).unwrap().role, KeyRole::DevTest);
        }
        assert_eq!(DEV_TEST_KEY_VAR, "PM_MODS_TEST_KEY");
    }

    #[test]
    fn dev_overrides_need_a_debug_build_pointed_elsewhere() {
        assert!(dev_overrides_allowed(true, true));
        assert!(!dev_overrides_allowed(true, false));
        assert!(!dev_overrides_allowed(false, true));
        assert!(!dev_overrides_allowed(false, false));
    }
}
